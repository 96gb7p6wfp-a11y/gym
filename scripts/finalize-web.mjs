import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const outputDir = path.resolve(process.argv[2] ?? path.join(projectRoot, 'dist'));
const workerFilename = 'service-worker.js';
const cachePrefix = 'setline-pwa-';

// Vite builds index.html and copies public/. Metadata belongs in the source HTML;
// this step only adds a worker derived from the finished, immutable build files.
await readFile(path.join(outputDir, 'index.html'));

async function listFiles(directory, relative = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const file = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(path.join(directory, entry.name), file));
    else if (entry.isFile() && file !== workerFilename && !file.endsWith('.map')) files.push(file);
    else if (entry.isSymbolicLink()) throw new Error(`Export contains an unexpected symbolic link: ${file}`);
  }
  return files.sort();
}

const files = await listFiles(outputDir);
const hash = createHash('sha256');
const optionalMedia = [];
for (const file of files) {
  const content = await readFile(path.join(outputDir, file));
  hash.update(file);
  hash.update('\0');
  hash.update(content);
  hash.update('\0');
  // Approved illustrations/photos are independent assets, never a mandatory
  // app-shell download. Only small, known build assets may be cached on demand.
  if (file.startsWith('exercise-media/') && /\.(?:webp|avif|svg|png|jpe?g)$/i.test(file) && content.byteLength <= 256_000) optionalMedia.push(file);
}
const version = hash.digest('hex').slice(0, 20);
const assetUrl = file => '/' + file.split('/').map(encodeURIComponent).join('/');
const urls = files.filter(file => !file.startsWith('exercise-media/')).map(assetUrl);

const worker = `// Generated by scripts/finalize-web.mjs. Cache only this origin's app shell.
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const MEDIA_CACHE = CACHE_NAME + '-media';
const MEDIA_PATHS = new Set(${JSON.stringify(optionalMedia.map(assetUrl))});
const MEDIA_CACHE_LIMIT = 24;
const PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};
const PRECACHE_PATHS = new Set(PRECACHE_URLS);

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      // addAll commits as one batch. Never activate a partially cached shell.
      await cache.addAll(PRECACHE_URLS.map((url) => new Request(url, { cache: 'reload' })));
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
    // Let an older open app finish using its existing asset version. The update
    // activates when those tabs close, so a session never loses its cached files.
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type !== 'SETLINE_ACTIVATE_UPDATE') return;
  event.waitUntil((async () => {
    // Another open window could contain a workout using the older cached
    // assets. Do not remove that cache while it still needs the old version.
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    if (windows.length > 1) {
      event.ports?.[0]?.postMessage({ accepted: false, reason: 'Close other Setline windows before updating.' });
      return;
    }
    event.ports?.[0]?.postMessage({ accepted: true });
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME && name !== MEDIA_CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  if (MEDIA_PATHS.has(url.pathname)) {
    event.respondWith((async () => {
      let cache;
      try {
        cache = await caches.open(MEDIA_CACHE);
        const cached = await cache.match(request);
        if (cached) return cached;
      } catch { /* Optional media remains usable when browser caches are denied. */ }
      try {
        const response = await fetch(request);
        if (cache && response.ok && response.headers.get('content-type')?.startsWith('image/')) {
          try {
            await cache.put(request, response.clone());
            const keys = await cache.keys();
            await Promise.all(keys.slice(0, Math.max(0, keys.length - MEDIA_CACHE_LIMIT)).map(key => cache.delete(key)));
          } catch { /* Media quota failures must never block training or saving. */ }
        }
        return response;
      } catch { return Response.error(); }
    })());
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.status < 500) return response;
      } catch {
        // The local bundle and persisted workout data remain usable offline.
      }
      const cache = await caches.open(CACHE_NAME);
      return await cache.match('/index.html') || await cache.match('/offline.html') ||
        new Response('Setline has not finished downloading. Reconnect once, then reopen the app.', {
          status: 503,
          headers: { 'Content-Type': 'text/plain; charset=utf-8' },
        });
    })());
    return;
  }

  if (PRECACHE_PATHS.has(url.pathname)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      return await cache.match(url.pathname) || fetch(request);
    })());
  }
});
`;
await writeFile(path.join(outputDir, workerFilename), worker);
console.log(`Finalized Setline PWA: ${urls.length} app files; ${optionalMedia.length} optional media assets (on demand only), cache ${cachePrefix}${version}.`);
